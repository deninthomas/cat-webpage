// Array Examples

// Example 1: Simple array
const colors = ["red", "blue", "green"];
console.log(colors[0]);  // Output: red
console.log(colors[1]);  // Output: blue
console.log(colors[2]);  // Output: green

// Example 2: Numbers array
const numbers = [10, 20, 30, 40, 50];
console.log(numbers[0]);  // Output: 10
console.log(numbers[2]);  // Output: 30
console.log(numbers[4]);  // Output: 50

// Example 3: Students names
const students = ["Ali", "Ahmed", "Fatima"];
console.log(students[0]);  // Output: Ali
console.log(students[1]);  // Output: Ahmed
console.log(students[2]);  // Output: Fatima