// Objects Examples

// Example 1: Person object
const person = {
  name: "Ali",
  age: 20,
  city: "Karachi"
};

console.log(person.name);   // Output: Ali
console.log(person.age);    // Output: 20
console.log(person.city);   // Output: Karachi

// Example 2: Car object
const car = {
  brand: "Honda",
  color: "red",
  year: 2020
};

console.log(car.brand);  // Output: Honda
console.log(car.color);  // Output: red
console.log(car.year);   // Output: 2020

// Example 3: Student object
const student = {
  name: "Ahmed",
  rollNumber: 123,
  marks: 85
};

console.log(student.name);       // Output: Ahmed
console.log(student.rollNumber); // Output: 123
console.log(student.marks);      // Output: 85