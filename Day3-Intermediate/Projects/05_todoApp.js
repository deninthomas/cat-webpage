// Todo Array App

// Example 1: Simple todo list
const todos = ["Buy milk", "Study", "Play"];
console.log(todos);
// Output: [Buy milk, Study, Play]

// Example 2: Add task
const tasks = ["Wake up", "Exercise"];
tasks.push("Breakfast");
tasks.push("Study");
console.log(tasks);
// Output: [Wake up, Exercise, Breakfast, Study]

// Example 3: Remove task
const activities = ["Run", "Read", "Eat"];
activities.pop();
console.log(activities);
// Output: [Run, Read]