// While Loop Examples

// Example 1: Print numbers 1 to 5
console.log("=== Print 1 to 5 ===");
let i = 1;
while (i <= 5) {
  console.log(i);
  i++;
}
// Output: 1, 2, 3, 4, 5

// Example 2: Print numbers backwards
console.log("=== Print 5 to 1 backwards ===");
let num = 5;
while (num >= 1) {
  console.log(num);
  num--;
}
// Output: 5, 4, 3, 2, 1

// Example 3: Countdown timer
console.log("=== Countdown ===");
let countdown = 5;
while (countdown > 0) {
  console.log(countdown);
  countdown--;
}
console.log("Blast off!");
// Output: 5, 4, 3, 2, 1, Blast off!
