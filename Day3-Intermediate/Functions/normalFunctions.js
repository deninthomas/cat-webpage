// Normal Function Examples

// Example 1: Simple function
function sayHello() {
  console.log("Hello!");
}

sayHello();  // Output: Hello!
sayHello();  // Output: Hello!

// Example 2: Function with numbers
function printAge() {
  const age = 20;
  console.log("Age is: " + age);
}

printAge();  // Output: Age is: 20

// Example 3: Function that adds numbers
function add() {
  const num1 = 10;
  const num2 = 5;
  const result = num1 + num2;
  console.log("Sum = " + result);
}

add();  // Output: Sum = 15