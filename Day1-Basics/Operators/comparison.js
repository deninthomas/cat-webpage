// Example 1: Greater than
const age = 20;
const canVote = age >= 18;
console.log(canVote);  // Output: true

// Example 2: Equal to
const password = "secret123";
const isCorrect = password === "secret123";
console.log(isCorrect);  // Output: true

// Example 3: Less than
const score = 45;
const isPassed = score >= 50;
console.log(isPassed);  // Output: false
