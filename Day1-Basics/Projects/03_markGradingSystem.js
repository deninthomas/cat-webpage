// Simple Mark Grading System

// Example 1: Marks 85 - Grade A
const marks1 = 85;
if (marks1 >= 80) {
  console.log("Grade: A");
} else if (marks1 >= 70) {
  console.log("Grade: B");
} else if (marks1 >= 60) {
  console.log("Grade: C");
} else if (marks1 >= 50) {
  console.log("Grade: D");
} else {
  console.log("Grade: F");
}
// Output: Grade: A

