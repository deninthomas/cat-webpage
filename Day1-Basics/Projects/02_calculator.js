// Simple Calculator

// Example 1: Addition
const a = 10;
const b = 5;
const sum = a + b;
console.log("10 + 5 = " + sum);
// Output: 10 + 5 = 15

// Example 2: Subtraction
const x = 20;
const y = 8;
const diff = x - y;
console.log("20 - 8 = " + diff);
// Output: 20 - 8 = 12

// Example 3: Multiplication
const num1 = 7;
const num2 = 6;
const product = num1 * num2;
console.log("7 * 6 = " + product);
// Output: 7 * 6 = 42
