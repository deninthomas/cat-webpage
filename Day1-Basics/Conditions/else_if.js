// Example 1: Grade system
const marks = 85;
if (marks >= 80) {
  console.log("Grade: A");
} else if (marks >= 60) {
  console.log("Grade: B");
} else {
  console.log("Grade: C");
}
// Output: Grade: A

// Example 2: Temperature ranges
const temp = 15;
if (temp > 30) {
  console.log("Very hot");
} else if (temp > 20) {
  console.log("Warm");
} else {
  console.log("Cold");
}
// Output: Cold

// Example 3: Time of day
const hour = 14;
if (hour < 12) {
  console.log("Good morning");
} else if (hour < 18) {
  console.log("Good afternoon");
} else {
  console.log("Good evening");
}
// Output: Good afternoon
